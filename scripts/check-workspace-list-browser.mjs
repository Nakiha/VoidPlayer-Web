import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { webkit } from 'playwright';
import { loadConfig } from '../server/config.ts';
import { startService } from '../server/runtime.ts';
import { Viewport } from '../src/viewport.ts';
const root = await mkdtemp(path.join(os.tmpdir(), 'vp-workspace-list-'));
let service, browser;
try {
  await mkdir(path.join(root, 'media'));
  const config = await loadConfig(['--folder', path.join(root, 'media'), '--data-dir', root], 'production'); config.port = 0; config.logsDir = null;
  service = await startService(config);
  browser = await webkit.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'dark' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${service.server.address().port}`);
  await page.locator('#identity-welcome input').fill('小明'); await page.locator('#identity-welcome .welcome-enter').click();
  await page.locator('#identity-welcome').waitFor({ state: 'hidden' });
  const document = { schema: 'voidplayer-workspace', version: 1, generatedAt: new Date().toISOString(), serverUrl: page.url(), positionUs: 0, tracks: [{ slot: 'A', mediaId: 'sample', offsetUs: 0 }], media: [{ id: 'sample', name: 'sample.mp4', size: 100, lastModified: 10, codec: 'h264', decoder: 'webcodecs', width: 100, height: 100, durationUs: 1000, firstPtsUs: 0 }], marks: [], viewport: new Viewport().snapshot(), layout: { panels: { inspector: true, subtracks: true, sources: true }, selected: 'A', dockHeight: 260, marksExpanded: true } };
  const save = name => page.evaluate(async ({name, document}) => { const r = await fetch('/api/workspaces', { method: 'POST', headers: { 'content-type': 'application/json', 'x-voidplayer-action': 'workspace' }, body: JSON.stringify({ name, document }) }); if (!r.ok) throw new Error(await r.text()); }, { name, document });
  await save('第一轮评审');
  await page.locator('#settings-open').click(); await page.locator('#settings-tab-identity').click();
  await page.locator('#identity-name').fill('小红'); await page.locator('#identity-save').click();
  await page.waitForFunction(() => document.querySelector('#identity-current').textContent === '小红');
  await save('第二轮评审'); await save('交付检查');
  await page.locator('#settings').screenshot({ path: '/tmp/vp-round2-identity.png' });
  await page.locator('#settings-tab-workspace').click();
  await page.waitForFunction(() => document.querySelectorAll('.saved-workspace-row').length === 3);
  const names = await page.locator('.saved-workspace-open strong').allTextContents(); assert.deepEqual(names, ['交付检查', '第二轮评审', '第一轮评审']);
  assert.equal(await page.locator('#workspace-import, #export, #saved-workspace-save').count(), 0);
  const colors = await page.locator('.saved-workspace-row').evaluateAll(rows => rows.map(r => getComputedStyle(r).backgroundColor)); assert.notEqual(colors[0], colors[1]);
  await page.locator('#settings').screenshot({ path: '/tmp/vp-round2-workspace.png' });
  await page.locator('#saved-workspace-search').fill('小明');
  await page.waitForFunction(() => document.querySelectorAll('.saved-workspace-row').length === 1);
  assert.equal(await page.locator('.saved-workspace-open strong').innerText(), '第一轮评审');
  await page.locator('#saved-workspace-search').fill('交付');
  await page.locator('.saved-workspace-open strong').filter({ hasText: '交付检查' }).waitFor();
  await page.locator('#saved-workspace-search-button').click(); await page.waitForFunction(() => document.querySelectorAll('.saved-workspace-row').length === 3);
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: 'light' });
  await page.locator('#settings').screenshot({ path: '/tmp/vp-round2-workspace-mobile.png' });
  assert.equal(await page.locator('#settings-pane-workspace').evaluate(e => e.scrollWidth > e.clientWidth), false);
  await page.locator('#settings-tab-identity').click();
  assert.equal(await page.locator('#settings-pane-identity').evaluate(e => e.scrollWidth > e.clientWidth), false);
  await page.locator('#settings').screenshot({ path: '/tmp/vp-round2-identity-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('PASS workspace list: owner/name live search, newest first, zebra rows, name and URI controls, fixed identity forms and mobile layout');
} finally { await browser?.close(); await service?.close(); await rm(root, { recursive: true, force: true }); }
